"""Generate the in-app help of appelbe-gui from the user guide: one source, docs/guide/gui-user.md.

The help window shows the guide's Markdown (FIGURE's markdown_view_object). The program cannot read the docs at run
time (a packaged program has no repository), so the text is compiled in: this script writes
src/gui/appelbe_gui_help.inc, the body of a Fortran function that builds the text line by line. The page is changed
on the way only where the window cannot follow the site: the YAML front matter is dropped, pictures are dropped (the
site shows them, the window does not), and a link to another page of the guide becomes its address on the site.

Usage:
    python3 scripts/gui_help.py            # write src/gui/appelbe_gui_help.inc
    python3 scripts/gui_help.py --check    # exit 1 when the include is not what the guide gives (run_gui_tests.sh)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GUIDE = ROOT / "docs" / "guide" / "gui-user.md"
INCLUDE = ROOT / "src" / "gui" / "appelbe_gui_help.inc"
SITE = "https://szaghi.github.io/appelbe/guide/"
CHUNK = 90  # bytes of UTF-8 text per Fortran literal: every source line stays below 132 bytes

IMAGE = re.compile(r"^!\[[^\]]*\]\([^)]*\)\s*$")
LINK = re.compile(r"\]\(([a-z0-9-]+)(#[a-z0-9-]+)?\)")


def help_markdown(guide: str) -> list[str]:
    """The guide's lines as the help window shows them."""
    lines = guide.splitlines()
    if lines and lines[0] == "---":
        end = lines.index("---", 1)
        lines = lines[end + 1 :]
    while lines and not lines[0].strip():
        lines = lines[1:]
    out: list[str] = []
    for line in lines:
        if IMAGE.match(line):
            continue
        out.append(LINK.sub(lambda m: "](" + SITE + m.group(1) + (m.group(2) or "") + ")", line))
    # no blank line left doubled where a picture was
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text).strip("\n")
    return text.split("\n")


def literal(text: str) -> str:
    """A Fortran character literal."""
    return "'" + text.replace("'", "''") + "'"


def split(line: str) -> list[str]:
    """The line in pieces of at most CHUNK bytes of UTF-8 (quotes count twice), never inside a character."""
    chunks: list[str] = []
    piece = ""
    for char in line:
        size = len(char.encode("utf-8")) * (2 if char == "'" else 1)
        if len((piece.replace("'", "''")).encode("utf-8")) + size > CHUNK:
            chunks.append(piece)
            piece = ""
        piece += char
    chunks.append(piece)
    return chunks


def include(lines: list[str]) -> str:
    """The include: statements appending each line, then a newline, to the result t."""
    out = [
        "! Generated by scripts/gui_help.py from docs/guide/gui-user.md: do not edit, run the script.",
        "t = ''",
    ]
    for line in lines:
        chunks = split(line)
        if len(chunks) == 1:
            out.append("t = t//" + literal(chunks[0]) + "//new_line('a')")
        else:
            out.append("t = t//" + literal(chunks[0]) + " &")
            out.extend("      //" + literal(chunk) + " &" for chunk in chunks[1:-1])
            out.append("      //" + literal(chunks[-1]) + "//new_line('a')")
    return "\n".join(out) + "\n"


def main() -> int:
    """Write the include, or check it."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="check the include instead of writing it")
    args = parser.parse_args()
    text = include(help_markdown(GUIDE.read_text(encoding="utf-8")))
    if args.check:
        current = INCLUDE.read_text(encoding="utf-8") if INCLUDE.exists() else ""
        if current != text:
            print(f"FAIL {INCLUDE.relative_to(ROOT)} is not the help of {GUIDE.relative_to(ROOT)}: "
                  "run python3 scripts/gui_help.py")
            return 1
        print(f"PASS {INCLUDE.relative_to(ROOT)} = the help of {GUIDE.relative_to(ROOT)}")
        return 0
    INCLUDE.write_text(text, encoding="utf-8")
    print(f"written {INCLUDE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
